const normalizeProduct = (product: Product): Product => ({
  ...product,
  code: product.code || product.id,
  condition: product.condition || product.specs.Condition || "With box (inbox)",
});
export const products: Product[] = seededProducts.map(normalizeProduct);

export const limitModelStorageVariants = (items: Product[]) => {
  const seen = new Map<string, Set<string>>();
  const familyCounts = new Map<string, number>();
  return items.filter((product) => {
    const model = product.name.trim().toLowerCase();
    const storage = (product.storageOptions[0]?.value || product.storageOptions[0]?.label || "default").trim().toLowerCase();
    const variants = seen.get(model) || new Set<string>();
    const family = product.brand === "apple" ? model.replace(/\s+(pro max|pro|plus|air)$/i, "") : model;
    const familyLimit = product.brand === "apple" ? 4 : 2;
    if (variants.has(storage) || variants.size >= 2) return false;
    if ((familyCounts.get(family) || 0) >= familyLimit) return false;
    variants.add(storage);
    seen.set(model, variants);
    familyCounts.set(family, (familyCounts.get(family) || 0) + 1);
    return true;
  });
};
export const publicProducts = limitModelStorageVariants(products).filter((product) => product.status !== "hidden" && product.imageRightsStatus !== "not_for_publication");
export const getProduct = (slug: string) => products.find((product) => product.slug === slug);
export const getPublicProduct = (slug: string) => publicProducts.find((product) => product.slug === slug);
export const formatPrice = (price: number, currency = "GHS") => price === 0 ? "Ask us" : new Intl.NumberFormat("en-GH", { style: "currency", currency, maximumFractionDigits: 0 }).format(price);
export const discountPercent = (_product: Product) => 0;

export const getCatalogProducts = (): Product[] => {
  if (typeof window === "undefined") return products;
  try {
    const raw = window.localStorage.getItem("natis-published-products");
    if (!raw) return products;
    const parsed = JSON.parse(raw) as Product[];
    return Array.isArray(parsed) && parsed.length > 0 ? limitModelStorageVariants(parsed.map(normalizeProduct)) : products;
  } catch {
    return products;
  }
};

export const getCatalogPublicProducts = () => limitModelStorageVariants(getCatalogProducts()).filter((product) => product.status !== "hidden" && product.imageRightsStatus !== "not_for_publication");
